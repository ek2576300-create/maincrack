export function createI18n(initial = 'ru') {
  let lang = initial === 'en' ? 'en' : 'ru';
  const listeners = new Set();
  const t = (key, fallback) => DICT[lang][key] ?? DICT.ru[key] ?? fallback ?? key;
  return {
    get lang() { return lang; },
    t,
    /** Pick the right half of a {ru, en} object. */
    pick: (obj) => (obj && typeof obj === 'object' ? (obj[lang] ?? obj.ru ?? obj.en) : obj),
    set(next) {
      const v = next === 'en' ? 'en' : 'ru';
      if (v === lang) return;
      lang = v;
      document.documentElement.lang = v;
      document.documentElement.dataset.lang = v;
      try { localStorage.setItem('kc.lang', v); } catch { /* private mode */ }
      document.cookie = `kc_lang=${v}; Path=/; Max-Age=${365 * 864e2}; SameSite=Lax`;
      listeners.forEach((fn) => fn(v));
    },
    onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); },
  };
}
